# 생선 분류 문제
# 생선 이름을 자동으로 알려주는 머신러닝 프로그램을 만들자.
"""
생선 데이터셋의 출처
https://www.kaggle.com/datasets/vipullrathod/fish-market
캐글은 2010년에 설립된 전 세계에서 가장 큰 머신러닝 경연대회 사이트이다.
대회 정보 뿐 아니라. 많은 데이터와 모델을 제공한다.
"""
# 머신러닝은 기준을 찾을 뿐만 아니라 이 기준을 이용해 생선이 도미인지 아닌지 판별할 수 있다.

# 도미 데이터 준비하기
# 머신러닝은 여러 개의 데이터를 보면서 스스로 구분할 기준을 찾는다.
# 그렇기에 학습시킬 데이터를 많이 준비시켜 놓아야 한다.

# 혼공머신은 35마리의 도미를 준비했다. 저울로 잰 도미의 길이(cm)와 무게(g)을 파이썬 리스트로 만들자

bream_length = [25.4, 26.3, 26.5, 29.0, 29.0, 29.7, 29.7, 30.0, 30.0, 30.7, 31.0, 31.0,
                31.5, 32.0, 32.0, 32.0, 33.0, 33.0, 33.5, 33.5, 34.0, 34.0, 34.5, 35.0,
                35.0, 35.0, 35.0, 36.0, 36.0, 37.0, 38.5, 38.5, 39.5, 41.0, 41.0]

bream_weight = [242.0, 290.0, 340.0, 363.0, 430.0, 450.0, 500.0, 390.0, 450.0, 500.0, 475.0, 500.0,
                500.0, 340.0, 600.0, 600.0, 700.0, 700.0, 610.0, 650.0, 575.0, 685.0, 620.0, 680.0,
                700.0, 725.0, 720.0, 714.0, 850.0, 1000.0, 920.0, 955.0, 925.0, 975.0, 950.0]

# 각 도미의 특징을 길이와 무게로 표현한 것을 이 책에서는 특성(feature)이라고 부른다.
# 두 특성을 숫자로 보는 것보다 그래프로 표현하면 데이터를 잘 이해할 수 있고 힌트도 얻을 수 있다.
# 길이를 x축으로 무게를 y축으로 정한 그래프(산점도)를 그리자

import matplotlib.pyplot as plt
plt.scatter(bream_length, bream_weight)
plt.xlabel('length')
plt.ylabel('weight')
plt.show()

# 이렇게 산점도 그래프가 일직선에 가까운 형태로 나타나는 경우를 선형적이라고 말한다.

# 빙어 데이터 준비하기
# 물류센터에 빙어가 많지 않아 혼공머신이 준비한 빙어는 14마리이다.

smelt_length = [9.8, 10.5, 10.6, 11.0, 11.2, 11.3, 11.8, 11.8, 12.0, 12.2, 12.4, 13.0, 14.3, 15.0]
smelt_weight = [6.7, 7.5, 7.0, 9.7, 9.8, 8.7, 10.0, 9.9, 9.8, 12.2, 13.4, 12.2, 19.7, 19.9]

# 마찬가지로 산점도를 그려보자

import matplotlib.pyplot as plt
plt.scatter(smelt_length, smelt_weight)
plt.scatter(bream_length, bream_weight)
plt.xlabel('length')
plt.ylabel('weight')
plt.show()

# 첫 번째 머신러닝 프로그램
# 여기에서는 가장 간단하고 이해하기 쉬운 k-최근접 이웃(k-nearest neighbors) 알고리즘을 사용해 도미와 빙어 데이터를 구분해보자
# k-최근접 이웃 알고리즘을 사용하기 전에 앞에서 준비했던 도미와 빙어 데이터를 하나의 데이터로 합치자

length = bream_length + smelt_length
weight = bream_weight + smelt_weight

# 이 책에서 사용하는 머신러닝 패키지는 사이킷런이다.
# 이 패키지를 사용하려면 각 특성의 리스트를 세로 방향으로 늘어뜨린 2차원 리스트를 만들어야 한다.
# 가장 쉬운 방법은 zip() 함수와 리스트 내포 구문을 사용하는 것이다.

fish_data = [[l,w] for l, w in zip(length, weight)]
print(fish_data)

# 마지막으로 준비해야할 데이터는 정답 데이터이다.
# 도미 = 1, 빙어 = 0 로 표현해서 리스트에 넣어놓자
fish_target = [1]*35 + [0]*14
print(fish_target)

# 이제 사이킷런 패키지에서 k-최근접 이웃 알고리즘을 구현한 클래스인 KNeighborsClassfier를 임포트하자.
from sklearn.neighbors import KNeighborsClassifier
# 임포트한 클래스의 객체를 만들자
kn = KNeighborsClassifier()

# 이 객체에 fish_data와 fish_target을 전달하여 도미를 찾기 위한 기준을 학습시키자
# 이런 과정을 훈련(training)이라고 부른다.
# 사이킷런에서는 fit() 메서드가 이 역할을 한다.

kn.fit(fish_data, fish_target)

# 이제 모델이 얼마나 잘 훈련되었는지 평가해보자
# 사이킷런에서 모델을 평가하는 메서드는 score() 메서드이다.
# 이 메서드는 0에서 1까지의 값을 반환한다. 1은 모든 데이터를 정확히 맞췄다는 것을 의미한다.

kn.score(fish_data, fish_target)

# 정확도가 1.0이다.

# K-최근접 이웃 알고리즘이란?
# 어떤 데이터에 대한 답을 구할 때 주위의 다른 데이터를 보고 다수를 차지하는 것을 정답으로 사용한다
# 그래프에서 (30,600)에 해당하는 값이 있다고 치자. 그러면 이 주위에는 도미가 많기 때문에 도미라고 판단한다.

# predict() 메서드는 새로운 데이터의 정답을 예측한다.
# 2차원 리스트를 전달해야 하기에 리스트로 두 번 감쌀 것이다.
# 이를 이용해 30,600을 도미와 방어 중 뭐로 생각하는지 평가해보자

kn.predict([[30,600]])

# 예상한 것처럼 도미로 예측했다.

# k-최근접 이웃 알고리즘이 준비해야 할 것은 데이터를 가지고 있는 게 전부이다.
# 새로운 데이터에 대해 예측할 때는 가장 가까운 직선거리에 어떤 데이터가 있는지를 살피기만 하면 된다.

# 단점은 k-최근접 이웃 알고리즘의 이런 특징 때문에 데이터가 아주 많은 경우에는
# 데이터가 크기 때문에 메모리가 많이 필요하고 직선거리를 계산하는 데도 많은 시간이 필요하다.

# 그럼 k-최근접 이웃 알고리즘은 주위 가까운 몇 개의 데이터를 참고할까?
# 기본값은 5이다. 이 기준은 n_neighbors 매개변수로 바꿀 수 있다.

kn49 = KNeighborsClassifier(n_neighbor=49) # 참고 데이터를 49개로 한 kn49모델
# 가장 가까운 데이터 49개를 사용하는 k-최근접 이웃 모델에 물고기 데이터를 적용하면 모든 데이터를 이용해 예측한다.
# 즉 도미가 35개있으므로 어떤 데이터를 넣어도 무조건 도미로 예측할 것이다.

# 이웃 인식 값이 어느선부터 정확도가 1 밑으로 떨어질까?

kn1 = KNeighborsClassifier()
kn1.fit(fish_data, fish_target)

for i in range(5,50):
  kn1.n_neighbors = i
  score = kn1.score(fish_data,fish_target)
  print(i, score)